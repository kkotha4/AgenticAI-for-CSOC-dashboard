// Login steps, invitations and the Users page.
// --- Login steps ------------------------------------------------------------
const postJson = (path, body) => fetch(path, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body || {}) });
const errorText = (res, body) => res.status === 429
  ? `${body.error || body.detail} Try again in ${res.headers.get("Retry-After")}s.` : (body.detail || "Something went wrong.");
function showLoginStep(id) {
  for (const s of ["login-form", "mfa-form", "enroll-form", "recovery-box", "invite-form", "invite-bad"]) $(`#${s}`).hidden = s !== id;
  $("#login").hidden = false;
}
async function nextLoginStep(next) {
  if (next === "done") { history.replaceState(null, "", location.pathname); location.reload(); return; }
  if (next === "mfa") { showLoginStep("mfa-form"); $("#mfa-code").focus(); return; }
  const res = await postJson("/api/auth/mfa/enroll");
  const body = await res.json();
  if (!res.ok) { showLoginStep("login-form"); $("#login-err").textContent = errorText(res, body); return; }
  $("#enroll-user").textContent = body.username;
  $("#enroll-qr").innerHTML = body.qr_svg;  // generated by our server from our own values
  $("#enroll-secret").textContent = body.secret;
  showLoginStep("enroll-form");
}
$("#login-form").onsubmit = async (ev) => {
  ev.preventDefault();
  const res = await postJson("/api/auth/login", { username: $("#user").value, password: $("#pass").value });
  const body = await res.json();
  $("#pass").value = "";
  if (res.ok) { $("#login-err").textContent = ""; nextLoginStep(body.next); return; }
  $("#login-err").textContent = errorText(res, body);
};
$("#mfa-form").onsubmit = async (ev) => {
  ev.preventDefault();
  const res = await postJson("/api/auth/mfa", { code: $("#mfa-code").value });
  const body = await res.json();
  $("#mfa-code").value = "";
  if (res.ok) { nextLoginStep("done"); return; }
  if (res.status === 401) { showLoginStep("login-form"); $("#login-err").textContent = body.detail; return; }
  $("#mfa-err").textContent = errorText(res, body);
};
$("#enroll-form").onsubmit = async (ev) => {
  ev.preventDefault();
  const res = await postJson("/api/auth/mfa/confirm", { code: $("#enroll-code").value });
  const body = await res.json();
  $("#enroll-code").value = "";
  if (res.status === 401) { showLoginStep("login-form"); $("#login-err").textContent = body.detail; return; }
  if (!res.ok) { $("#enroll-err").textContent = errorText(res, body); return; }
  const list = $("#recovery-codes"); list.textContent = "";
  body.recovery_codes.forEach((code) => { const d = document.createElement("div"); d.textContent = code; list.appendChild(d); });
  showLoginStep("recovery-box");
};
$("#recovery-saved").onchange = (ev) => { $("#recovery-done").disabled = !ev.target.checked; };
$("#recovery-done").onclick = () => nextLoginStep("done");

let inviteToken = null;
async function startInvite(token) {
  inviteToken = token;
  const res = await postJson("/api/invites/lookup", { token });
  const body = await res.json();
  if (!res.ok) { $("#invite-bad").textContent = errorText(res, body); showLoginStep("invite-bad"); return; }
  $("#invite-user").textContent = body.username;
  $("#invite-role").textContent = body.role;
  showLoginStep("invite-form");
}
$("#invite-form").onsubmit = async (ev) => {
  ev.preventDefault();
  if ($("#invite-pass").value !== $("#invite-pass2").value) { $("#invite-err").textContent = "Those passwords don't match."; return; }
  const res = await postJson("/api/invites/accept", { token: inviteToken, password: $("#invite-pass").value });
  const body = await res.json();
  if (!res.ok) { $("#invite-err").textContent = errorText(res, body); return; }
  history.replaceState(null, "", location.pathname);  // the link has done its job
  $("#invite-pass").value = $("#invite-pass2").value = "";
  nextLoginStep(body.next);
};

// --- Users page ---------------------------------------------------------------
function actionButton(label, fn) {
  const b = document.createElement("button"); b.textContent = label; b.onclick = fn; return b;
}
function buildTable(box, heads, rows) {
  box.textContent = "";
  const t = document.createElement("table"), hr = t.createTHead().insertRow(), tb = t.createTBody();
  heads.forEach((h) => { const th = document.createElement("th"); th.textContent = h; hr.appendChild(th); });
  rows.forEach((cells) => {
    const r = tb.insertRow();
    cells.forEach((c) => { const td = r.insertCell(); if (c instanceof Node) td.appendChild(c); else td.textContent = c; });
  });
  box.appendChild(t);
}
async function usersAction(method, path, done) {
  const res = await api(path, { method });
  const body = await res.json();
  const msg = $("#users-msg");
  msg.className = res.ok ? "msg" : "msg err";
  msg.textContent = res.ok ? done : (body.detail || "That didn't work.");
  loadUsers();
}
async function loadUsers() {
  const data = await (await api("/api/users")).json();
  const select = $("#new-role");
  if (!select.options.length) {
    data.roles.forEach((r) => select.add(new Option(r, r)));
    select.value = "viewer";  // least privilege by default: granting more should be a deliberate choice
  }
  if (data.invites.length) buildTable($("#invites-table"), ["Username", "Role", "Invited by", "Expires", ""], data.invites.map((i) => [
    i.username, i.role, i.invited_by, new Date(i.expires_at * 1000).toLocaleString(),
    actionButton("Revoke", () => usersAction("DELETE", `/api/users/invites/${encodeURIComponent(i.username)}`, `Invitation for ${i.username} revoked.`)),
  ]));
  else $("#invites-table").innerHTML = '<p class="empty">No open invitations.</p>';
  buildTable($("#users-table"), ["Username", "Role", "MFA", ""], data.users.map((u) => {
    const actions = document.createElement("div");
    actions.style.cssText = "display:flex;gap:6px;flex-wrap:wrap";
    if (u.you) actions.textContent = "You";
    else {
      // The first click arms the button, so a slip can't remove someone. The viewer shows no dialogs.
      const confirmTwice = (label, method, path, done) => {
        const b = actionButton(label, () => {
          if (b.dataset.armed) usersAction(method, path, done);
          else { b.dataset.armed = "1"; b.textContent = `Confirm: ${label.toLowerCase()}`; }
        });
        return b;
      };
      const name = encodeURIComponent(u.username);
      if (u.mfa_enabled) actions.appendChild(confirmTwice("Reset MFA", "POST", `/api/users/${name}/reset-mfa`, `MFA reset for ${u.username}. They'll set it up at next login.`));
      actions.appendChild(confirmTwice("Remove", "DELETE", `/api/users/${name}`, `${u.username} removed.`));
    }
    return [u.username, u.role, u.mfa_enabled ? "On" : "Not set up", actions];
  }));
}
$("#new-invite").onsubmit = async (ev) => {
  ev.preventDefault();
  const res = await api("/api/users/invites", { method: "POST", headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ username: $("#new-user").value, role: $("#new-role").value }) });
  const body = await res.json();
  const msg = $("#invite-msg");
  $("#invite-result").hidden = !res.ok;
  msg.className = res.ok ? "msg" : "msg err";
  msg.textContent = res.ok ? `Invitation created for ${body.username}.` : body.detail;
  if (res.ok) {
    $("#invite-link").textContent = `${location.origin}${location.pathname}#invite/${body.token}`;
    $("#invite-hours").textContent = body.expires_hours;
    $("#new-user").value = "";
    loadUsers();
  }
};
$("#logout").onclick = async () => { await fetch("/api/auth/logout", { method: "POST" }); location.reload(); };

